"""Validate editable English task content and generate the C++ task component.

Uses only the Python standard library. Run from any directory.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def validate(data):
    tasks = data.get("tasks") if isinstance(data, dict) else None
    if not isinstance(tasks, list) or len(tasks) != 4:
        raise ValueError("The game requires exactly four task tabs.")
    ids = set()
    for task in tasks:
        if not isinstance(task, dict):
            raise ValueError("Each task must be an object.")
        for key, limit in (("id", 40), ("title", 23), ("subtitle", 70)):
            value = task.get(key)
            if not isinstance(value, str) or not value.strip() or len(value) > limit:
                raise ValueError(f"Invalid {key}; expected 1-{limit} characters.")
            if not value.isascii() or not value.isprintable():
                raise ValueError(f"{key} must use printable English/ASCII text for GLUT fonts.")
        if task["id"] in ids:
            raise ValueError("Task IDs must be unique.")
        ids.add(task["id"])
        steps = task.get("steps")
        if not isinstance(steps, list) or len(steps) != 3:
            raise ValueError("Every tab requires exactly three example steps.")
        for step in steps:
            if not isinstance(step, str) or not step.strip() or len(step) > 62:
                raise ValueError("Each example step must contain 1-62 characters.")
            if not step.isascii() or not step.isprintable():
                raise ValueError("Steps must use printable English/ASCII text.")
    return tasks


def generate(data):
    tasks = validate(data)
    rows = []
    for task in tasks:
        steps = ", ".join(json.dumps(step) for step in task["steps"])
        rows.append("    Task{" + json.dumps(task["title"]) + ", "
                    + json.dumps(task["subtitle"]) + ", {" + steps + "}, 0, false}")
    return ("// Generated by tools/generate_tasks.py from assets/tasks.json.\n"
            "#pragma once\ninline std::array<Task, 4> makeTasks() {\n"
            "  return std::array<Task, 4>{{\n" + ",\n".join(rows) + "\n  }};\n}\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Validate without writing a header")
    args = parser.parse_args()
    try:
        data = json.loads((ROOT / "assets/tasks.json").read_text(encoding="utf-8"))
        header = generate(data)
        if not args.check:
            (ROOT / "task_data.hpp").write_text(header, encoding="utf-8")
        print("PASS: four English task tabs, unique IDs, three steps each, safe text lengths")
    except (ValueError, OSError) as error:
        parser.exit(1, f"Task content error: {error}\n")


if __name__ == "__main__":
    main()
